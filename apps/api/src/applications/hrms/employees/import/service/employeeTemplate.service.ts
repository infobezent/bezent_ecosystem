export class EmployeeTemplateService {
  constructor(private readonly orgRepo = new OrganizationRepository()) {}

  async generateWorkbook(
    tenantId: string,
    companyId: string,
    type: 'basic' | 'complete' = 'basic',
  ): Promise<ExcelJS.Workbook> {
    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'BEZENT HRMS';
    workbook.lastModifiedBy = 'BEZENT Import Engine';
    workbook.created = new Date();
    workbook.modified = new Date();

    const columns = type === 'complete' ? COMPLETE_TEMPLATE_COLUMNS : BASIC_TEMPLATE_COLUMNS;

    // Fetch dynamic reference data for company
    const masters = await this.orgRepo.getMasters(tenantId, companyId);

    // ----------------------------------------------------
    // Sheet 1: Employee Data
    // ----------------------------------------------------
    const dataSheet = workbook.addWorksheet('Employee Data', {
      views: [{ state: 'frozen', ySplit: 1 }],
    });

    dataSheet.columns = columns.map((col) => ({
      header: col.header,
      key: col.key,
      width: col.width,
    }));

    // Style header row
    const headerRow = dataSheet.getRow(1);
    headerRow.height = 26;
    headerRow.font = { bold: true, color: { argb: 'FF0F172A' }, size: 11, name: 'Segoe UI' };
    headerRow.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FFF1F5F9' },
    };
    headerRow.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true };
    headerRow.border = {
      bottom: { style: 'medium', color: { argb: 'FFCBD5E1' } },
    };

    // Add 1 sample / illustrative row
    const sampleRow: Record<string, string> = {};
    for (const col of columns) {
      sampleRow[col.key] = col.example;
    }
    const row2 = dataSheet.addRow(sampleRow);
    row2.font = { italic: true, color: { argb: 'FF64748B' }, size: 10, name: 'Segoe UI' };

    // ----------------------------------------------------
    // Sheet 2: Instructions
    // ----------------------------------------------------
    const instructionsSheet = workbook.addWorksheet('Instructions');
    instructionsSheet.columns = [
      { header: 'Column Name', key: 'colName', width: 26 },
      { header: 'Required', key: 'required', width: 16 },
      { header: 'Description', key: 'desc', width: 50 },
      { header: 'Accepted Format / Example', key: 'format', width: 30 },
    ];

    const instHeader = instructionsSheet.getRow(1);
    instHeader.height = 24;
    instHeader.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 };
    instHeader.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF1E293B' },
    };

    instructionsSheet.addRow({
      colName: '--- GENERAL RULES ---',
      required: '',
      desc: '1. Do not rename, remove, or reorder column headers.\n2. Enter one employee per row.\n3. Dates must be formatted as YYYY-MM-DD (e.g. 2026-01-15).\n4. Department, Designation, and Work Location must match the Reference Data sheet exactly.\n5. Leave optional fields blank if details are unavailable.',
      format: '',
    });

    for (const col of columns) {
      instructionsSheet.addRow({
        colName: col.header,
        required: col.required,
        desc: col.description,
        format: col.example,
      });
    }

    // ----------------------------------------------------
    // Sheet 3: Reference Data
    // ----------------------------------------------------
    const refSheet = workbook.addWorksheet('Reference Data');
    refSheet.columns = [
      { header: 'Valid Departments', key: 'departments', width: 28 },
      { header: 'Valid Designations', key: 'designations', width: 28 },
      { header: 'Valid Work Locations', key: 'locations', width: 28 },
      { header: 'Employment Types', key: 'employmentTypes', width: 22 },
      { header: 'Employee Statuses', key: 'employeeStatuses', width: 22 },
    ];

    const refHeader = refSheet.getRow(1);
    refHeader.height = 24;
    refHeader.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 };
    refHeader.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF0284C7' },
    };

    const employmentTypes = ['Full-Time', 'Part-Time', 'Contract', 'Intern'];
    const employeeStatuses = ['Active', 'Probation', 'Pending Activation'];

    const maxRows = Math.max(
      masters.departments.length,
      masters.designations.length,
      masters.locations.length,
      employmentTypes.length,
      employeeStatuses.length,
      1,
    );

    for (let i = 0; i < maxRows; i++) {
      refSheet.addRow({
        departments: masters.departments[i]?.name ?? '',
        designations: masters.designations[i]?.name ?? '',
        locations: masters.locations[i]?.name ?? '',
        employmentTypes: employmentTypes[i] ?? '',
        employeeStatuses: employeeStatuses[i] ?? '',
      });
    }

    return workbook;
  }

  async generateBuffer(
    tenantId: string,
    companyId: string,
    type: 'basic' | 'complete' = 'basic',
  ): Promise<Buffer> {
    const workbook = await this.generateWorkbook(tenantId, companyId, type);
    const buffer = await workbook.xlsx.writeBuffer();
    return Buffer.from(buffer);
  }

  async generateCsv(
    tenantId: string,
    companyId: string,
    type: 'basic' | 'complete' = 'basic',
  ): Promise<string> {
    const workbook = await this.generateWorkbook(tenantId, companyId, type);
    const dataSheet = workbook.getWorksheet('Employee Data');
    if (!dataSheet) return '';

    const lines: string[] = [];
    dataSheet.eachRow({ includeEmpty: false }, (row) => {
      const values = row.values as Array<unknown>;
      const line = values
        .slice(1)
        .map((val) => {
          if (val === null || val === undefined) return '""';
          const str = String(val).replace(/"/g, '""');
          return `"${str}"`;
        })
        .join(',');
      lines.push(line);
    });
    return lines.join('\n');
  }
}
