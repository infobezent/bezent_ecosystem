CREATE TABLE IF NOT EXISTS `leave_policies` (
	`id` varchar(64) NOT NULL,
	`tenant_id` varchar(64) NOT NULL,
	`company_id` varchar(64) NOT NULL,
	`name` varchar(100) NOT NULL,
	`code` varchar(20) NOT NULL,
	`description` text,
	`status` enum('draft','active','scheduled','archived') NOT NULL DEFAULT 'draft',
	`scope` enum('company','department','location','employment_type','custom') NOT NULL DEFAULT 'company',
	`scope_id` varchar(64),
	`scope_name` varchar(100),
	`effective_from` varchar(10) NOT NULL,
	`effective_to` varchar(10),
	`linked_leave_type_ids` json NOT NULL,
	`priority` int NOT NULL DEFAULT 0,
	`is_active` boolean NOT NULL DEFAULT true,
	`created_by_user_id` varchar(64) NOT NULL,
	`created_at` timestamp NOT NULL DEFAULT (now()),
	`updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `leave_policies_id` PRIMARY KEY(`id`),
	CONSTRAINT `idx_leave_policies_company_code` UNIQUE(`company_id`,`code`),
	INDEX `idx_leave_policies_tenant_comp` (`tenant_id`,`company_id`),
	INDEX `idx_leave_policies_status` (`status`),
	INDEX `idx_leave_policies_scope` (`scope`,`scope_id`),
	INDEX `idx_leave_policies_effective` (`effective_from`,`effective_to`),
	CONSTRAINT `leave_policies_company_id_companies_id_fk` FOREIGN KEY (`company_id`) REFERENCES `companies`(`id`) ON DELETE no action ON UPDATE no action
);
